const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];
const stripEmoji = (s) => s.replace(/[\p{Extended_Pictographic}\uFE0F]/gu, "").trim();

/**
 * يبني توجيهاً ارتجالياً لكيفية الرد (كذب / محايد / صدق) اعتماداً على بطاقة اللاعب — دون أي نص جاهز من JSON.
 * displayHtml: للعرض على الشاشة (يبرز الجريمة الجانبية).
 * speechText : للنطق فقط (لا يتضمن المصلحة السرية ولا اسم الجريمة الجانبية إطلاقاً).
 */
export function buildImprovisationGuidance(responseType, roleCard) {
    const type = GUIDANCE.guilty[responseType] ? responseType : "neutral";
    const category = classifyRole(roleCard);
    const crime = category === "side_crime" ? extractSideCrime(roleCard.secret_interest) : "";
    const template = pick(GUIDANCE[category][type]);
    const title = TITLES[type];

    const bodyDisplay = escapeHtml(template.body).replace(
        /\{crime\}/g,
        `<b style="color:#ff9b9b;">«${escapeHtml(crime)}»</b>`
    );
    const bodySpeech = template.body.replace(/\{crime\}/g, "جريمتك الجانبية");

    return {
        title,
        category,
        bodyHtml: bodyDisplay,
        tipText: template.tip,
        speechText: `${stripEmoji(title)}. ${bodySpeech} نصيحة: ${template.tip}`
    };
}
